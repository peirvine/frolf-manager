// Writes src/version.js before start, build and test so the footer can show which build is running.
// Semantic version worked out from the commit history, so nothing is bumped by hand. It starts from the version in
// package.json (as of the commit that last changed it) and then reads each commit since, oldest first, by its
// Conventional Commit type (see checkCommitMsg.js):
//   breaking change ("type!:" or a BREAKING CHANGE footer) -> major + 1, minor and patch reset
//   feat                                                   -> minor + 1, patch resets
//   anything else                                          -> patch + 1
// To jump to a chosen version, edit "version" in package.json and commit. The short commit hash is detail.
// `node scripts/writeVersion.js --print` just prints the version (the release workflow uses it).
const { execSync } = require('child_process')
const fs = require('fs')
const path = require('path')

const git = (args) => { try { return execSync(`git ${args}`, { stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024 }).toString().trim() } catch { return '' } }

let [major, minor, patch] = require('../package.json').version.split('.').map(Number)
const baseline = git('log -1 --format=%H -G"^\\s*\\"version\\":" -- package.json')

const SEPARATOR = '\x1e'
const log = baseline ? git(`log --reverse --format=%B${SEPARATOR} ${baseline}..HEAD`) : ''
for (const message of log.split(SEPARATOR).map(text => text.trim()).filter(Boolean)) {
  const header = message.split('\n')[0]
  if (/^\w+(\([^)]*\))?!:/.test(header) || /^BREAKING[ -]CHANGE:/m.test(message)) { major += 1; minor = 0; patch = 0 }
  else if (/^feat(\([^)]*\))?:/.test(header)) { minor += 1; patch = 0 }
  else patch += 1
}

const version = {
  version: `${major}.${minor}.${patch}`,
  commit: git('rev-parse --short HEAD'),
  builtAt: new Date().toISOString().slice(0, 10),
}

if (process.argv.includes('--print')) {
  console.log(version.version)
  process.exit(0)
}

fs.writeFileSync(path.join(__dirname, '../src/version.js'), `// Generated by scripts/writeVersion.js. Do not edit or commit.\nconst buildInfo = ${JSON.stringify(version, null, 2)}\n\nexport default buildInfo\n`)
